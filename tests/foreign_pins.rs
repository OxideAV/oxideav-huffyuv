/// Encoder side of the first-pixel rule: the frame starts `00 B G R`
/// with the plain pixel, decodes back, and for LEFT + decorrelation
/// opens with the same four bytes the third-party encoder wrote for
/// this raster.
#[test]
fn encoder_stores_the_first_rgb_pixel_plain() {
    let bottom_up: Vec<u8> = RGB24_LEFT_4X3_PIXELS
        .as_chunks::<12>()
        .0
        .iter()
        .rev()
        .flatten()
        .copied()
        .collect();
    for mode in [ExtradataMode::ClassicV2, ExtradataMode::CustomV2] {
        for method in [Method::LeftDecorr, Method::GradientDecorr] {
            let (strf, frame) =
                encode_frame_with_mode(PixelFamily::Rgb24, method, 4, 3, &bottom_up, mode).unwrap();
            assert_eq!(frame[0], 0, "pad byte (spec/03 §6 #6)");
            assert_eq!(&frame[1..4], &bottom_up[..3], "plain B G R");
            let (_, pixels) = decode_top_down(&strf, &frame);
            assert_eq!(pixels, RGB24_LEFT_4X3_PIXELS);
        }
    }
    // Same residual stream as the third-party encoder: with LEFT +
    // decorrelation the first four bytes are identical.
    assert_eq!(
        &encode_frame_with_mode(
            PixelFamily::Rgb24,
            Method::LeftDecorr,
            4,
            3,
            &bottom_up,
            ExtradataMode::ClassicV2
        )
        .unwrap()
        .1[..4],
        &RGB24_LEFT_4X3_FRAME[..4]
    );
}

